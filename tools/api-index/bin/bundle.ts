// bundle: writes the one-file shopware-api.mjs the skills ship, so an agent
// runs `diff` and `facts` with plain Node from the installed skill folder:
// no clone of this repo, no npm install.
//
//   node tools/api-index/bin/bundle.ts            # write every copy
//   node tools/api-index/bin/bundle.ts --check    # fail when a copy is stale (CI)
//   node tools/api-index/bin/bundle.ts --out <file>  # one more copy, e.g. for the npm package
//
// The copies are identical, so git stores them once.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { build } from 'esbuild';
import { errorMessage } from '../../src/errors.ts';
import { MIN_NODE } from '../src/main-cli.ts';

const root = resolve(import.meta.dirname, '../../..');

/** The skills whose references run the script. */
export const SKILLS = ['sw-change-impact', 'sw-core-development', 'sw-extension-review', 'sw-plugin-development'];

const HEADER = `#!/usr/bin/env node
// shopware-api.mjs: GENERATED by tools/api-index/bin/bundle.ts, do not edit.
// Source: https://github.com/BrocksiNet/ai-skills-shopware/tree/main/tools/api-index
// Run: node shopware-api.mjs --help (Node ${MIN_NODE} or newer).
// Bundles php-parser (BSD-3-Clause, (c) 2014 Glayzzle), @babel/parser (MIT,
// (c) 2012-2014 its contributors) and yaml (ISC, (c) Eemeli Aro).
`;

// yaml is CommonJS and calls require(); an ESM bundle has none of its own.
const REQUIRE = "import{createRequire as __cr}from'node:module';const require=__cr(import.meta.url);";

export async function bundle(): Promise<string> {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['tools/api-index/bin/shopware-api.ts'],
    bundle: true,
    minify: true,
    platform: 'node',
    format: 'esm',
    target: `node${MIN_NODE}`,
    banner: { js: REQUIRE },
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  const [file] = result.outputFiles;
  if (file === undefined) throw new Error('esbuild wrote no output');
  return `${HEADER}${file.text}`;
}

export const targets = (): string[] =>
  SKILLS.map((skill) => join(root, 'skills', skill, 'scripts', 'shopware-api.mjs'));

async function main(): Promise<number> {
  const { values } = parseArgs({
    options: { check: { type: 'boolean', default: false }, out: { type: 'string' } },
  });
  const text = await bundle();
  const files = values.out === undefined ? targets() : [resolve(values.out)];
  if (values.check) {
    const stale = files.filter((file) => !existsSync(file) || readFileSync(file, 'utf8') !== text);
    for (const file of stale) process.stderr.write(`stale: ${relative(root, file)}\n`);
    if (stale.length > 0) process.stderr.write('Run: node tools/api-index/bin/bundle.ts\n');
    return stale.length === 0 ? 0 : 1;
  }
  for (const file of files) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text, { mode: 0o755 });
    process.stdout.write(`wrote ${relative(root, file)} (${Math.round(text.length / 1024)} KB)\n`);
  }
  return 0;
}

try {
  process.exitCode = await main();
} catch (error) {
  process.stderr.write(`bundle: ${errorMessage(error)}\n`);
  process.exitCode = 1;
}
