// bundle: writes the one-file shopware-api.mjs of the `shopware-api-index`
// npm package. The skills run it with `npx -y shopware-api-index@<version>`,
// pinned to the version in npm/package.json.
//
//   node tools/api-index/bin/bundle.ts               # write npm/shopware-api.mjs
//   node tools/api-index/bin/bundle.ts --out <file>  # write it elsewhere
//   node tools/api-index/bin/bundle.ts --check       # every skill pins the package version (CI)
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { build } from 'esbuild';
import { errorMessage } from '../../src/errors.ts';
import { MIN_NODE } from '../src/main-cli.ts';

const root = resolve(import.meta.dirname, '../../..');

const PACKAGE = 'shopware-api-index';

const HEADER = `#!/usr/bin/env node
// shopware-api.mjs: GENERATED by tools/api-index/bin/bundle.ts, do not edit.
// Source: https://github.com/BrocksiNet/ai-skills-shopware/tree/main/tools/api-index
// Run: node shopware-api.mjs --help (Node ${MIN_NODE} or newer).
// Bundles php-parser (BSD-3-Clause, (c) 2014 Glayzzle), @babel/parser (MIT,
// (c) 2012-2014 its contributors) and yaml (ISC, (c) Eemeli Aro).
`;

// yaml is CommonJS and calls require(); an ESM bundle has none of its own.
const REQUIRE = "import{createRequire as __cr}from'node:module';const require=__cr(import.meta.url);";

export async function bundle(): Promise<string> {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['tools/api-index/bin/shopware-api.ts'],
    bundle: true,
    minify: true,
    platform: 'node',
    format: 'esm',
    target: `node${MIN_NODE}`,
    banner: { js: REQUIRE },
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  const [file] = result.outputFiles;
  if (file === undefined) throw new Error('esbuild wrote no output');
  return `${HEADER}${file.text}`;
}

/** The version in npm/package.json, the one the skills must pin. */
export function packageVersion(): string {
  const json: unknown = JSON.parse(readFileSync(join(root, 'tools/api-index/npm/package.json'), 'utf8'));
  const version = typeof json === 'object' && json !== null && 'version' in json ? json.version : undefined;
  if (typeof version !== 'string') throw new TypeError('npm/package.json has no version');
  return version;
}

/** Skill markdown that runs the package unpinned, on another version, or still names a bundled copy. */
export function pinErrors(skillsDir: string, version: string): string[] {
  const errors: string[] = [];
  const walk = (dir: string): void => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (entry.name.endsWith('.md')) {
        const text = readFileSync(path, 'utf8');
        const at = relative(root, path);
        if (text.includes('scripts/shopware-api.mjs')) errors.push(`${at}: names scripts/shopware-api.mjs`);
        for (const match of text.matchAll(/npx(?: -y)? shopware-api-index(@\S+)?/gu)) {
          const pinned = match[1]?.slice(1);
          if (pinned !== version) errors.push(`${at}: ${match[0]} (want ${PACKAGE}@${version})`);
        }
      }
    }
  };
  walk(skillsDir);
  return errors;
}

async function main(): Promise<number> {
  const { values } = parseArgs({
    options: { check: { type: 'boolean', default: false }, out: { type: 'string' } },
  });
  if (values.check) {
    const errors = pinErrors(join(root, 'skills'), packageVersion());
    for (const error of errors) process.stderr.write(`${error}\n`);
    return errors.length === 0 ? 0 : 1;
  }
  const text = await bundle();
  const file = resolve(values.out ?? join(root, 'tools/api-index/npm/shopware-api.mjs'));
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text, { mode: 0o755 });
  process.stdout.write(`wrote ${relative(root, file)} (${Math.round(text.length / 1024)} KB)\n`);
  return 0;
}

try {
  process.exitCode = await main();
} catch (error) {
  process.stderr.write(`bundle: ${errorMessage(error)}\n`);
  process.exitCode = 1;
}
